const _accent = PdfColor.fromInt(0xFF8B3A5A);
const _muted = PdfColor.fromInt(0xFF666666);
const _band = PdfColor.fromInt(0xFFEFE6EA);
const _rule = PdfColor.fromInt(0xFFDDDDDD);

/// Builds the printable doctor report.
Future<Uint8List> buildPdfReport(
  ReportData data, {
  required pw.Font regular,
  required pw.Font bold,
  PdfPageFormat pageFormat = PdfPageFormat.a4,
}) {
  final day = DateFormat.yMMMd();
  final short = DateFormat.MMMd();
  final o = data.options;
  final doc = pw.Document(
    title: 'Menstrual cycle report',
    creator: 'Comma',
    theme: pw.ThemeData.withFont(base: regular, bold: bold),
  );

  pw.Widget heading(String text) => pw.Padding(
    padding: const pw.EdgeInsets.only(top: 18, bottom: 6),
    child: pw.Text(
      text,
      style: pw.TextStyle(
        fontSize: 13,
        fontWeight: pw.FontWeight.bold,
        color: _accent,
      ),
    ),
  );

  pw.Widget table(List<String> headers, List<List<String>> rows) =>
      pw.TableHelper.fromTextArray(
        headers: headers,
        data: rows,
        border: const pw.TableBorder(
          horizontalInside: pw.BorderSide(color: _rule, width: 0.5),
          bottom: pw.BorderSide(color: _rule, width: 0.5),
        ),
        headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 9),
        cellStyle: const pw.TextStyle(fontSize: 9),
        headerAlignment: pw.Alignment.centerLeft,
        cellAlignment: pw.Alignment.centerLeft,
        headerDecoration: const pw.BoxDecoration(color: _band),
        cellPadding: const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 3),
      );

  pw.Widget fact(String label, String value) => pw.Padding(
    padding: const pw.EdgeInsets.symmetric(vertical: 2),
    child: pw.Row(
      children: [
        pw.SizedBox(
          width: 170,
          child: pw.Text(label, style: const pw.TextStyle(color: _muted)),
        ),
        pw.Expanded(child: pw.Text(value)),
      ],
    ),
  );

  final stats = data.stats;
  final complete = data.cycles
      .where((r) => r.cycle.isComplete)
      .toList(growable: false);

  doc.addPage(
    pw.MultiPage(
      pageFormat: pageFormat,
      margin: const pw.EdgeInsets.all(40),
      footer: (context) => pw.Row(
        children: [
          pw.Expanded(
            child: pw.Text(
              'Generated by Comma from self-reported data. Predictions are '
              'estimates, not a diagnosis.',
              style: const pw.TextStyle(fontSize: 7, color: _muted),
            ),
          ),
          pw.Text(
            'Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 7, color: _muted),
          ),
        ],
      ),
      build: (context) => [
        pw.Text(
          'Menstrual cycle report',
          style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold),
        ),
        pw.SizedBox(height: 4),
        pw.Text(
          [
            if (o.name != null && o.name!.trim().isNotEmpty) o.name!.trim(),
            '${day.format(o.from)} – ${day.format(o.to)}',
            'generated ${day.format(data.generated)}',
          ].join('  ·  '),
          style: const pw.TextStyle(color: _muted),
        ),

        heading('Summary'),
        fact('Cycles in this period', '${data.cycles.length}'),
        if (stats != null) ...[
          fact(
            'Average cycle length',
            '${stats.cycleLength.toStringAsFixed(1)} days',
          ),
          if (data.lengthRange case final r?)
            fact(
              'Shortest / longest cycle',
              '${r.shortest} / ${r.longest} days',
            ),
          fact('Typical period length', '${stats.periodLength} days'),
        ] else
          fact('Average cycle length', 'Not enough complete cycles'),
        if (data.cycles.isNotEmpty)
          fact('Last period started', day.format(data.cycles.last.cycle.start)),
        if (data.nextPeriod case final p?)
          fact(
            'Next period expected',
            '${day.format(p.periodStart)} (${short.format(p.earliestStart)} – ${short.format(p.latestStart)})',
          ),

        if (data.flags.isNotEmpty) ...[
          heading('Patterns worth discussing'),
          for (final f in data.flags)
            pw.Bullet(
              text: _flagText(f, short),
              style: const pw.TextStyle(fontSize: 10),
            ),
        ],

        if (data.cycles.isNotEmpty) ...[
          heading('Cycle history'),
          table(
            ['Started', 'Cycle length', 'Period', 'Heaviest flow', 'Ovulation'],
            [
              for (final r in data.cycles)
                [
                  day.format(r.cycle.start),
                  r.cycle.length == null ? 'current' : '${r.cycle.length} days',
                  '${r.cycle.periodLength} days',
                  _flowName(r.heaviestFlow),
                  if (r.ovulation case final ov?)
                    '${short.format(ov.date)} (${ov.source == OvulationSource.bbt ? 'temperature' : 'LH test'})'
                  else
                    '–',
                ],
            ],
          ),
        ],

        if (complete.isNotEmpty) ...[
          heading('Cycle lengths'),
          pw.Text(
            'Tick marks show the typical range of 24–38 days',
            style: const pw.TextStyle(fontSize: 8, color: _muted),
          ),
          pw.SizedBox(height: 6),
          for (final r in complete)
            _lengthBar(r.cycle.start, r.cycle.length!, short),
        ],

        if (data.symptoms.isNotEmpty) ...[
          heading('Symptoms'),
          table(
            ['Symptom', 'Days logged', 'Cycles with it', 'Usually'],
            [
              for (final s in data.symptoms)
                [
                  s.label,
                  '${s.days}',
                  '${s.cyclesWith} of ${data.cycles.length}',
                  s.usualPhase == null ? '–' : _phaseName(s.usualPhase!),
                ],
            ],
          ),
        ],

        if (data.pregnancyTests.isNotEmpty) ...[
          heading('Pregnancy tests'),
          for (final (date, result) in data.pregnancyTests)
            fact(
              day.format(date),
              result == TestResult.negative ? 'Negative' : 'Positive',
            ),
        ],

        if (data.sex case final s?) ...[
          heading('Sexual activity'),
          fact('Partnered sex', _times(s.partnered)),
          fact('Without protection', _times(s.unprotected)),
          fact('Masturbation', _times(s.solo)),
        ],

        if (data.notes.isNotEmpty) ...[
          heading('Notes'),
          for (final (date, note) in data.notes)
            pw.Padding(
              padding: const pw.EdgeInsets.only(bottom: 4),
              child: pw.Row(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.SizedBox(
                    width: 80,
                    child: pw.Text(
                      short.format(date),
                      style: const pw.TextStyle(color: _muted),
                    ),
                  ),
                  pw.Expanded(child: pw.Text(note)),
                ],
              ),
            ),
        ],
      ],
    ),
  );
  return doc.save();
}

pw.Widget _lengthBar(DateTime start, int length, DateFormat fmt) {
  const scaleMax = 60.0;
  final value = length.clamp(0, scaleMax).toDouble();
  return pw.Padding(
    padding: const pw.EdgeInsets.symmetric(vertical: 1.5),
    child: pw.Row(
      children: [
        pw.SizedBox(
          width: 60,
          child: pw.Text(
            fmt.format(start),
            style: const pw.TextStyle(fontSize: 8, color: _muted),
          ),
        ),
        pw.Expanded(
          child: pw.LayoutBuilder(
            builder: (context, constraints) {
              final w = constraints!.maxWidth;
              pw.Widget tick(double days) => pw.Positioned(
                left: w * days / scaleMax - 0.5,
                top: -2,
                child: pw.Container(width: 1, height: 14, color: _muted),
              );
              return pw.Stack(
                overflow: pw.Overflow.visible,
                children: [
                  pw.Container(width: w, height: 10, color: _band),
                  pw.Container(
                    width: w * value / scaleMax,
                    height: 10,
                    decoration: const pw.BoxDecoration(
                      color: _accent,
                      borderRadius: pw.BorderRadius.horizontal(
                        right: pw.Radius.circular(2),
                      ),
                    ),
                  ),
                  tick(24),
                  tick(38),
                ],
              );
            },
          ),
        ),
        pw.SizedBox(
          width: 50,
          child: pw.Text(
            '  $length days',
            style: const pw.TextStyle(fontSize: 8),
          ),
        ),
      ],
    ),
  );
}

String _times(int n) => n == 1 ? '1 time' : '$n times';

String _flowName(FlowLevel f) => switch (f) {
  FlowLevel.none => '–',
  FlowLevel.spotting => 'Spotting',
  FlowLevel.light => 'Light',
  FlowLevel.medium => 'Medium',
  FlowLevel.heavy => 'Heavy',
};

String _phaseName(Phase p) => switch (p) {
  Phase.period => 'During period',
  Phase.follicular => 'After period',
  Phase.fertile => 'Fertile window',
  Phase.ovulation => 'Around ovulation',
  Phase.luteal => 'Before period',
};

String _flagText(Irregularity f, DateFormat fmt) {
  final when = f.cycleStart == null
      ? ''
      : ' (cycle starting ${fmt.format(f.cycleStart!)})';
  return switch (f.kind) {
    IrregularityKind.shortCycle => 'Short cycle of ${f.days} days$when',
    IrregularityKind.longCycle => 'Long cycle of ${f.days} days$when',
    IrregularityKind.highVariability =>
      'Cycle lengths varied by ${f.days} days across recent cycles',
    IrregularityKind.longPeriod => 'Bleeding lasted ${f.days} days$when',
    IrregularityKind.missedPeriods =>
      'No period for ${f.days} days since ${fmt.format(f.cycleStart!)}',
  };
}
